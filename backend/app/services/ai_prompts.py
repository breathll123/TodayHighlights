def item_user_prompt(*, title: str, source_name: str, published_at: str, body: str) -> str:
    return (
        "请基于以下股票主题内容生成结构化摘要。\n\n"
        "输出必须是 JSON 对象，字段和约束如下：\n"
        "- title: 字符串，1-60 字，概括事件本身，不夸张。\n"
        "- summary: 字符串，20-180 字，中性说明事件和可能影响。\n"
        "- tags: 字符串数组，0-5 个，每个不超过 12 字。\n"
        "- related_symbols: 字符串数组，0-10 个，每个不超过 20 字；没有明确标的则返回空数组。\n"
        "- importance_score: 整数，0-100；按信息重要性、时效性、影响范围、可验证性评分。\n"
        "- focus_points: 字符串数组，1-3 个，每个不超过 80 字；写值得继续关注的事实或变量。\n"
        "- risk_points: 字符串数组，0-3 个，每个不超过 80 字；写不确定性、信息不足或潜在风险。\n\n"
        "评分参考：\n"
        "- 80-100: 影响范围大、时效强、与多只标的或板块相关。\n"
        "- 50-79: 有明确事件或异动，但影响范围有限。\n"
        "- 20-49: 信息较普通、来源单一或缺少关键细节。\n"
        "- 0-19: 内容很短、重复、噪音或无法判断。\n\n"
        "输入内容：\n"
        f"标题：{title}\n"
        f"来源：{source_name}\n"
        f"发布时间：{published_at}\n"
        f"正文：{body[:4000]}"
    )


def topic_user_prompt(context_json: str) -> str:
    return (
        "请基于以下股票主题上下文生成今日看点。\n\n"
        "输入包含：单条 AI 加工结果列表、榜单/行情异动列表。\n"
        "请从中提炼 3 到 5 条今日重点，不要逐条复述输入。\n\n"
        "输出必须是 JSON 对象，字段和约束如下：\n"
        "- title: 字符串，1-40 字，概括今日整体看点。\n"
        "- items: 数组，3-5 条。\n"
        "  每条 item 包含：\n"
        "  - title: 字符串，1-60 字。\n"
        "  - reason: 字符串，20-120 字，说明为什么重要。\n"
        "  - related: 字符串数组，0-8 个，每个不超过 20 字。\n"
        "  - risk: 字符串，0-100 字；没有明确风险可为空字符串。\n"
        "  - source_refs: 整数数组，保留引用来源 ID，最多 10 个。\n\n"
        "选择规则：\n"
        "- 优先选择影响范围大、时效强、与市场异动有关的内容。\n"
        "- 如果多条内容属于同一主题，合并成一条看点。\n"
        "- 不要输出买卖建议，不要预测价格或涨跌。\n"
        "- 不要编造 source_refs，只能使用输入里存在的来源 ID。\n\n"
        f"上下文：\n{context_json}"
    )